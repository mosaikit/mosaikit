/// Format of the `.mskp` packages (architecture §8.5).
const MSKP_FORMAT: u32 = 3;
/// Image of the Docker development kit, published by the release workflow next to the normal one.
const DEV_IMAGE: &str = "ghcr.io/mosaikit/mosaikit-dev";

pub struct Options {
    pub out: Option<PathBuf>,
    /// use the executables already built in `target/release` (no `cargo build`, no `npm run build`)
    pub skip_build: bool,
    /// include `mosaikit-server` on platforms where it is not included by default
    pub with_server: bool,
    /// add the API reference generated by `cargo doc` for the SDK
    pub api_docs: bool,
    /// sign with the development key when `MOSAIKIT_SIGNING_KEY` is missing (never for a real release)
    pub allow_dev_key: bool,
}

fn read(p: &Path) -> Result<String> {
    std::fs::read_to_string(p).with_context(|| format!("reading {}", p.display()))
}

fn toml_of(p: &Path) -> Result<toml::Value> {
    Ok(toml::from_str(&read(p)?)?)
}

fn workspace_version() -> Result<String> {
    let t = toml_of(&root().join("Cargo.toml"))?;
    t["workspace"]["package"]["version"].as_str().map(str::to_string).context("workspace version")
}

fn package_json(dir: &str) -> Result<Value> {
    Ok(serde_json::from_str(&read(&root().join(dir).join("package.json"))?)?)
}

/// What the notes and the compatibility table say, read from the manifests of the repository.
pub struct Facts {
    pub version: String,
    pub sdk: String,
    pub plugin_api: String,
    pub testing: String,
    pub api: u32,
    pub rust: String,
    /// (id, version, `[requires] mosaikit`, `[requires] api`) of the plugins of the kit and the official ones
    pub plugins: Vec<(String, String, String, String)>,
    /// (component, text of its changelog for this version, or of `Unreleased`)
    pub changes: Vec<(String, String)>,
}

/// The text of `## <version>` (or `## Unreleased` as a fallback) of a changelog, up to the next `## `.
pub fn changelog_section(text: &str, version: &str) -> Option<String> {
    let pick = |head: &str| {
        let mut on = false;
        let mut out: Vec<&str> = Vec::new();
        for l in text.lines() {
            if let Some(h) = l.strip_prefix("## ") {
                if on {
                    break;
                }
                on = h.trim() == head;
                continue;
            }
            if on {
                out.push(l);
            }
        }
        on.then(|| out.join("\n").trim().to_string())
    };
    pick(version).or_else(|| pick("Unreleased")).filter(|s| !s.is_empty())
}

/// The «Breaking changes» (a `### Breaking changes` heading inside the section of a changelog) of a section.
pub fn breaking_of(section: &str) -> Option<String> {
    let mut on = false;
    let mut out: Vec<&str> = Vec::new();
    for l in section.lines() {
        if l.starts_with('#') {
            if on {
                break;
            }
            on = l.trim_start_matches('#').trim().eq_ignore_ascii_case("breaking changes");
            continue;
        }
        if on {
            out.push(l);
        }
    }
    let t = out.join("\n").trim().to_string();
    (!t.is_empty()).then_some(t)
}

/// The section of a changelog without its «Breaking changes» part.
fn without_breaking(section: &str) -> String {
    let mut skip = false;
    let mut out: Vec<&str> = Vec::new();
    for l in section.lines() {
        if l.starts_with('#') {
            skip = l.trim_start_matches('#').trim().eq_ignore_ascii_case("breaking changes");
            if skip {
                continue;
            }
        }
        if !skip {
            out.push(l);
        }
    }
    out.join("\n").trim().to_string()
}

pub fn render_compat(f: &Facts) -> String {
    let mut t = String::new();
    t.push_str(&format!("# Compatibility of the kit {}\n\n", f.version));
    t.push_str("Generated from the manifests of the repository at the release; do not edit.\n\n");
    t.push_str("| Piece | Version |\n|---|---|\n");
    t.push_str(&format!("| Mosaikit platform and dev kit (`mosaikit-plugin`) | {} |\n", f.version));
    t.push_str(&format!("| Plugin API | {} |\n| Logic ABI | {} |\n", f.api, f.api));
    t.push_str(&format!("| SDK `mosaikit-plugin-sdk` | {} |\n", f.sdk));
    t.push_str(&format!("| UI package `@mosaikit/plugin-api` | {} |\n", f.plugin_api));
    t.push_str(&format!("| Test helpers `@mosaikit/plugin-testing` | {} |\n", f.testing));
    t.push_str(&format!("| Package format `.mskp` | {MSKP_FORMAT} |\n| Rust (minimum) | {} |\n\n", f.rust));
    t.push_str("## Plugins of this release\n\nThe version of the platform each plugin asks for, as its manifest says.\n\n");
    t.push_str("| Plugin | Version | `[requires] mosaikit` | `[requires] api` | Works with this kit |\n|---|---|---|---|---|\n");
    for (id, v, req, api) in &f.plugins {
        let ok = match (
            mosaikit_mskp::VersionReq::parse(req),
            mosaikit_mskp::Version::parse_lenient(&f.version),
        ) {
            (Some(r), Some(ver)) if api.parse::<u32>().map_or(true, |a| a <= f.api) && r.matches(ver) => {
                "yes"
            }
            (None, _) if req == "-" => "no range declared",
            _ => "no",
        };
        t.push_str(&format!("| {id} | {v} | {req} | {api} | {ok} |\n"));
    }
    t
}

pub fn render_notes(f: &Facts) -> String {
    let mut t = format!("# Mosaikit dev kit {}\n\n", f.version);
    t.push_str(&format!(
        "Plugin API {api}, SDK {}, UI package {}, test helpers {}. Compatibility table: COMPATIBILITY.md. Update an installed kit with `mosaikit-plugin self-update`.\n\n",
        f.sdk, f.plugin_api, f.testing, api = f.api
    ));
    // one heading, so that `self-update` reads the whole of it
    let breaking: Vec<String> =
        f.changes.iter().filter_map(|(c, s)| breaking_of(s).map(|b| format!("**{c}**\n\n{b}"))).collect();
    t.push_str("## Breaking changes\n\n");
    if breaking.is_empty() {
        t.push_str("None.\n\n");
    } else {
        t.push_str(&breaking.join("\n\n"));
        t.push_str("\n\n");
    }
    t.push_str("## Changes\n\n");
    for (c, s) in &f.changes {
        let body = without_breaking(s);
        if !body.is_empty() {
            t.push_str(&format!("**{c}**\n\n{body}\n\n"));
        }
    }
    t
}

/// The text with every `{{name}}` replaced by `x`.
fn fill_placeholders(s: &str) -> String {
    let mut out = String::new();
    let mut rest = s;
    while let Some(i) = rest.find("{{") {
        out.push_str(&rest[..i]);
        match rest[i..].find("}}") {
            Some(j) => {
                out.push('x');
                rest = &rest[i + j + 2..];
            }
            None => {
                rest = &rest[i..];
                break;
            }
        }
    }
    out.push_str(rest);
    out
}

/// Reads the facts from the repository (and from the plugins of the kit and, when it is there, of `mosaikit-plugins`).
pub fn facts() -> Result<Facts> {
    let version = workspace_version()?;
    let ws = toml_of(&root().join("Cargo.toml"))?;
    let sdk = toml_of(&root().join("crates/plugin-sdk/Cargo.toml"))?["package"]["version"]
        .as_str()
        .context("sdk version")?
        .to_string();
    let jv = |d: &str| package_json(d).map(|j| j["version"].as_str().unwrap_or("?").to_string());
    let mut plugins_found: Vec<(String, String, String, String)> = Vec::new();
    let mut dirs: Vec<PathBuf> = std::fs::read_dir(root().join("crates/plugin-cli/templates/examples"))?
        .flatten()
        .map(|e| e.path())
        .collect();
    if let Ok(all) = plugins::discover() {
        dirs.extend(all.into_iter().map(|p| p.dir));
    }
    for d in dirs {
        // an example is a template: its `{{placeholders}}` are replaced so that the manifest parses
        let Ok(t) = std::fs::read_to_string(d.join("plugin.toml"))
            .map_err(anyhow::Error::from)
            .and_then(|s| Ok(toml::from_str::<toml::Value>(&fill_placeholders(&s))?))
        else {
            continue;
        };
        let g = |k: &str| t.get(k).and_then(|v| v.as_str()).unwrap_or("-").to_string();
        let r = t.get("requires");
        let rs = |k: &str| {
            r.and_then(|r| r.get(k))
                .map(|v| v.as_str().map(str::to_string).unwrap_or_else(|| v.to_string()))
                .unwrap_or_else(|| "-".into())
        };
        let id = match g("id") {
            // the examples are templates: their id is a placeholder
            i if i.starts_with("{{") || i == "x" => format!(
                "example {}",
                d.file_name().map(|n| n.to_string_lossy().to_string()).unwrap_or_default()
            ),
            i => i,
        };
        plugins_found.push((id, g("version"), rs("mosaikit"), rs("api")));
    }
    plugins_found.sort();
    plugins_found.dedup();
    let mut changes = Vec::new();
    for (name, path) in [
        ("mosaikit-plugin (CLI)", "crates/plugin-cli/CHANGELOG.md"),
        ("mosaikit-plugin-sdk", "crates/plugin-sdk/CHANGELOG.md"),
        ("@mosaikit/plugin-api", "ui/plugin-api/CHANGELOG.md"),
        ("@mosaikit/plugin-testing", "ui/plugin-testing/CHANGELOG.md"),
        ("mosaikit-mskp", "crates/mskp/CHANGELOG.md"),
        ("mosaikit-sql-guard", "crates/sql-guard/CHANGELOG.md"),
    ] {
        if let Some(s) = changelog_section(&read(&root().join(path))?, &version).or_else(|| {
            // the packages that have their own number
            let own = match path {
                "crates/plugin-sdk/CHANGELOG.md" => Some(sdk.clone()),
                "ui/plugin-api/CHANGELOG.md" => jv("ui/plugin-api").ok(),
                "ui/plugin-testing/CHANGELOG.md" => jv("ui/plugin-testing").ok(),
                _ => None,
            }?;
            changelog_section(&read(&root().join(path)).ok()?, &own)
        }) {
            changes.push((name.to_string(), s));
        }
    }
    Ok(Facts {
        plugin_api: jv("ui/plugin-api")?,
        testing: jv("ui/plugin-testing")?,
        api: mosaikit_mskp::API_VERSION,
        rust: ws["workspace"]["package"]["rust-version"].as_str().unwrap_or("?").to_string(),
        version,
        sdk,
        plugins: plugins_found,
        changes,
    })
}

/// One licence line per package: (name, version, licence, repository).
pub type Pkg = (String, String, String, String);

/// Third-party crates of the executables of the kit (normal dependencies, from `cargo metadata`).
pub fn crates_of(meta: &Value, roots: &[&str]) -> Vec<Pkg> {
    let pk = |id: &str| meta["packages"].as_array().and_then(|a| a.iter().find(|p| p["id"] == id));
    let nodes: BTreeMap<&str, &Value> = meta["resolve"]["nodes"]
        .as_array()
        .map(|a| a.iter().filter_map(|n| Some((n["id"].as_str()?, n))).collect())
        .unwrap_or_default();
    let mut todo: Vec<String> = meta["packages"]
        .as_array()
        .map(|a| {
            a.iter()
                .filter(|p| roots.contains(&p["name"].as_str().unwrap_or("")))
                .filter_map(|p| p["id"].as_str().map(str::to_string))
                .collect()
        })
        .unwrap_or_default();
    let mut seen: std::collections::BTreeSet<String> = todo.iter().cloned().collect();
    let mut out = Vec::new();
    while let Some(id) = todo.pop() {
        let Some(n) = nodes.get(id.as_str()) else { continue };
        for d in n["deps"].as_array().into_iter().flatten() {
            let normal = d["dep_kinds"].as_array().is_some_and(|k| k.iter().any(|k| k["kind"].is_null()));
            let Some(did) = d["pkg"].as_str() else { continue };
            if normal && seen.insert(did.to_string()) {
                todo.push(did.to_string());
            }
        }
    }
    for id in &seen {
        let Some(p) = pk(id) else { continue };
        if p["source"].is_null() {
            continue; // a crate of this workspace
        }
        let s = |k: &str| p[k].as_str().unwrap_or("").to_string();
        out.push((
            s("name"),
            s("version"),
            if s("license").is_empty() { "see the crate".into() } else { s("license") },
            s("repository"),
        ));
    }
    out.sort();
    out
}

pub fn render_notices(version: &str, crates: &[Pkg], npm_pkgs: &[(Pkg, String)]) -> String {
    let mut t = format!("# Third-party notices of the Mosaikit dev kit {version}\n\n");
    t.push_str("Mosaikit is licensed under the Apache License 2.0 (file LICENSE). The kit bundles or builds on the components below,\n");
    t.push_str("each under its own licence. The list is generated from `cargo metadata` (the executables of the kit) and from the\n");
    t.push_str("`package.json` files of the UI package; `cargo deny check licenses` enforces the allow-list of `deny.toml`.\n\n");
    let mut by: BTreeMap<&str, usize> = BTreeMap::new();
    for c in crates {
        *by.entry(c.2.as_str()).or_default() += 1;
    }
    t.push_str("## Rust crates\n\n| Licence | Crates |\n|---|---|\n");
    for (l, n) in &by {
        t.push_str(&format!("| {l} | {n} |\n"));
    }
    t.push_str("\n| Crate | Version | Licence | Source |\n|---|---|---|---|\n");
    for (n, v, l, r) in crates {
        t.push_str(&format!("| {n} | {v} | {l} | {r} |\n"));
    }
    t.push_str(
        "\n## npm packages of the UI\n\n| Package | Version | Licence | Source |\n|---|---|---|---|\n",
    );
    for ((n, v, l, r), _) in npm_pkgs {
        t.push_str(&format!("| {n} | {v} | {l} | {r} |\n"));
    }
    for ((n, _, l, _), text) in npm_pkgs {
        if !text.trim().is_empty() {
            t.push_str(&format!("\n### Licence text of {n} ({l})\n\n```\n{}\n```\n", text.trim()));
        }
    }
    t
}

/// Runs `cargo metadata`, the npm licence report and (when installed) `cargo deny check licenses`; returns the text.
pub fn notices() -> Result<String> {
    let meta = output(Command::new("cargo").current_dir(root()).args([
        "metadata",
        "--format-version",
        "1",
        "--locked",
    ]))?;
    let meta: Value = serde_json::from_str(&meta)?;
    let crates = crates_of(&meta, &["mosaikit-plugin-cli", "mosaikit-server"]);
    let mut npm_pkgs = Vec::new();
    let api = package_json("ui/plugin-api")?;
    for name in
        api["dependencies"].as_object().map(|d| d.keys().cloned().collect::<Vec<_>>()).unwrap_or_default()
    {
        let dir = root().join("node_modules").join(&name);
        let Ok(j) = serde_json::from_str::<Value>(&read(&dir.join("package.json")).unwrap_or_default())
        else {
            bail!("{name} is not installed (npm ci): the licence report needs node_modules");
        };
        let s = |k: &str| j[k].as_str().unwrap_or("").to_string();
        let text = ["LICENSE", "LICENSE.md", "LICENSE.txt"]
            .iter()
            .find_map(|f| std::fs::read_to_string(dir.join(f)).ok())
            .unwrap_or_default();
        let repo = j["repository"]["url"].as_str().or(j["repository"].as_str()).unwrap_or("").to_string();
        npm_pkgs.push(((name.clone(), s("version"), s("license"), repo), text));
    }
    if which("cargo-deny").is_some() {
        run(Command::new("cargo").current_dir(root()).args(["deny", "check", "licenses"]))?;
    } else {
        eprintln!("warning: cargo-deny is not installed: the licences were listed but not checked (cargo install cargo-deny)");
    }
    Ok(render_notices(&workspace_version()?, &crates, &npm_pkgs))
}

fn platform() -> String {
    update::platform()
}

/// Archive name and the executables the kit holds on this platform.
fn include_server(o: &Options) -> bool {
    o.with_server || cfg!(windows)
}

fn untar(archive: &Path, dest: &Path) -> Result<()> {
    std::fs::create_dir_all(dest)?;
    run(update::tar().arg("-xf").arg(archive).arg("-C").arg(dest))
}

fn release_key(o: &Options) -> Result<ed25519_dalek::SigningKey> {
    let have = std::env::var("MOSAIKIT_SIGNING_KEY").is_ok_and(|k| !k.trim().is_empty())
        || std::env::var("MOSAIKIT_SIGNING_KEY_FILE").is_ok_and(|f| Path::new(&f).is_file());
    if !have && !o.allow_dev_key {
        bail!("no signing key: set MOSAIKIT_SIGNING_KEY (the key of the official packages), or use --allow-dev-key for a local trial that nobody should trust");
    }
    let (key, source) = plugins::signing_key()?;
    eprintln!("signing the kit with: {source}");
    Ok(key)
}

/// `SHA256SUMS` and `SHA256SUMS.sig` for the kit archives in `dir`.
pub fn write_sums(dir: &Path, key: &ed25519_dalek::SigningKey) -> Result<()> {
    let mut entries = Vec::new();
    for e in std::fs::read_dir(dir)?.flatten() {
        let name = e.file_name().to_string_lossy().to_string();
        if name.starts_with("mosaikit-devkit-") && (name.ends_with(".zip") || name.ends_with(".tar.gz")) {
            entries.push((update::sha256_hex(&std::fs::read(e.path())?), name));
        }
    }
    if entries.is_empty() {
        bail!("no kit archive (mosaikit-devkit-*.zip, *.tar.gz) in {}", dir.display());
    }
    let sums = update::sums_text(&entries);
    std::fs::write(dir.join(update::SUMS_FILE), &sums)?;
    std::fs::write(dir.join("SHA256SUMS.sig"), update::sign_bytes(key, sums.as_bytes()))?;
    Ok(())
}

/// `release devkit-sums <dir>`: the checksums and their signature over the archives of every platform (the last
/// job of the workflow, after the platforms have uploaded theirs).
pub fn sums_only(dir: &Path, allow_dev_key: bool) -> Result<()> {
    let key = release_key(&Options {
        out: None,
        skip_build: true,
        with_server: false,
        api_docs: false,
        allow_dev_key,
    })?;
    write_sums(dir, &key)?;
    println!("SHA256SUMS and SHA256SUMS.sig written in {}", dir.display());
    Ok(())
}

