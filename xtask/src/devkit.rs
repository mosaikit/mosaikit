//! `cargo xtask release devkit`: the release of the plugin development kit (phase 7 of docs/plugin-devkit-plan.md).
//!
//! One archive per platform: `bin/` (the CLI `mosaikit-plugin`, and the server `mosaikit-server` where it exists
//! today: Windows), `sdk/` (the unpacked `.crate` of the SDK) and `plugin-api/` (the unpacked `npm pack` tarball),
//! `docs/devkit`, `examples/`, `docker/` (the compose folder of the Docker development kit), the licences, the
//! release notes and the compatibility table generated from the manifests. Next to the archive: its signature,
//! `SHA256SUMS` and its signature. Signed with the key of the official packages (`MOSAIKIT_SIGNING_KEY`).

