/// The kit: folder, archive, signature, sums.
pub fn devkit(o: &Options) -> Result<()> {
    let version = workspace_version()?;
    let platform = platform();
    let server = include_server(o);
    let key = release_key(o)?;
    let out = o.out.clone().unwrap_or_else(|| root().join("dist").join("devkit"));
    let name = format!("mosaikit-devkit-{version}-{platform}");
    let kit = out.join(&name);
    if kit.exists() {
        std::fs::remove_dir_all(&kit)?;
    }
    std::fs::create_dir_all(kit.join("bin"))?;
    let tmp = out.join(".work");
    if tmp.exists() {
        std::fs::remove_dir_all(&tmp)?;
    }
    std::fs::create_dir_all(&tmp)?;

    // --- executables ---
    if !o.skip_build {
        let mut b = Command::new("cargo");
        b.current_dir(root()).args(["build", "--release", "-p", "mosaikit-plugin-cli"]);
        if server {
            plugins::ensure_npm()?;
            run(npm().current_dir(root()).args(["run", "build"]))?;
            b.args(["-p", "mosaikit-server"]);
        }
        run(&mut b)?;
    }
    let rel = plugins::target_dir().join("release");
    let mut bins = vec!["mosaikit-plugin"];
    if server {
        bins.push("mosaikit-server");
    }
    for b in bins {
        std::fs::copy(rel.join(exe(b)), kit.join("bin").join(exe(b))).with_context(|| {
            format!("copying {} from {} (build it, or drop --skip-build)", exe(b), rel.display())
        })?;
    }

    // --- the packages of D1: the unpacked .crate and the unpacked npm tarball ---
    run(Command::new("cargo").current_dir(root()).args([
        "package",
        "-p",
        "mosaikit-plugin-sdk",
        "--allow-dirty",
        "--no-verify",
    ]))?;
    let crate_file = plugins::target_dir().join("package").join(format!(
        "mosaikit-plugin-sdk-{}.crate",
        toml_of(&root().join("crates/plugin-sdk/Cargo.toml"))?["package"]["version"]
            .as_str()
            .context("sdk version")?
    ));
    untar(&crate_file, &tmp.join("crate"))?;
    let unpacked = std::fs::read_dir(tmp.join("crate"))?
        .flatten()
        .map(|e| e.path())
        .find(|p| p.is_dir())
        .context("empty .crate")?;
    copy_dir(&unpacked, &kit.join("sdk"))?;
    run(npm()
        .current_dir(root().join("ui").join("plugin-api"))
        .args(["pack", "--pack-destination"])
        .arg(&tmp))?;
    let tgz = std::fs::read_dir(&tmp)?
        .flatten()
        .map(|e| e.path())
        .find(|p| p.extension().is_some_and(|e| e == "tgz"))
        .context("npm pack made no tarball")?;
    untar(&tgz, &tmp.join("npm"))?;
    copy_dir(&tmp.join("npm").join("package"), &kit.join("plugin-api"))?;

    // --- documents, examples, Docker kit ---
    copy_dir(&root().join("docs").join("devkit"), &kit.join("docs").join("devkit"))?;
    std::fs::copy(root().join("docs").join("architecture.md"), kit.join("docs").join("architecture.md"))?;
    if o.api_docs {
        run(Command::new("cargo").current_dir(root()).args([
            "doc",
            "-p",
            "mosaikit-plugin-sdk",
            "--no-deps",
        ]))?;
        copy_dir(&plugins::target_dir().join("doc"), &kit.join("docs").join("api").join("sdk"))?;
    }
    copy_dir(&root().join("crates/plugin-cli/templates/examples"), &kit.join("examples"))?;
    let pg =
        crate::dist::current().docker.postgres_image.clone().unwrap_or_else(|| "postgres:17-alpine".into());
    crate::release::devkit_folder(&kit.join("docker"), DEV_IMAGE, &version, &pg)?;

    // --- licences, notes, compatibility ---
    std::fs::copy(root().join("LICENSE"), kit.join("LICENSE"))?;
    std::fs::write(kit.join("THIRD-PARTY-NOTICES.md"), notices()?)?;
    let f = facts()?;
    std::fs::write(kit.join("RELEASE-NOTES.md"), render_notes(&f))?;
    std::fs::write(kit.join("COMPATIBILITY.md"), render_compat(&f))?;
    std::fs::write(kit.join("VERSION"), format!("{version}\n"))?;
    std::fs::write(kit.join(update::TRUSTED_KEY_FILE), mosaikit_mskp::public_key_b64(&key) + "\n")?;
    std::fs::write(kit.join("KIT.txt"), kit_txt(&version, &platform, server))?;
    std::fs::remove_dir_all(&tmp)?;

    // --- archive, signatures ---
    let archive = out.join(update::archive_name(&version, &platform));
    if platform.starts_with("windows") {
        crate::release::zip_dir(&kit, &name, &archive)?;
    } else {
        run(update::tar().arg("-czf").arg(&archive).arg("-C").arg(&out).arg(&name))?;
    }
    let sig_name = format!("{}.sig", archive.file_name().context("archive name")?.to_string_lossy());
    std::fs::write(out.join(sig_name), update::sign_bytes(&key, &std::fs::read(&archive)?))?;
    std::fs::write(out.join("RELEASE-NOTES.md"), std::fs::read(kit.join("RELEASE-NOTES.md"))?)?;
    write_sums(&out, &key)?;
    println!(
        "\ndev kit: {}\narchive: {}\nchecksums: {}",
        kit.display(),
        archive.display(),
        out.join(update::SUMS_FILE).display()
    );
    Ok(())
}

/// `release devkit-notes --out <folder>`: RELEASE-NOTES.md and COMPATIBILITY.md alone (no build).
pub fn notes_only(out: &Path) -> Result<()> {
    std::fs::create_dir_all(out)?;
    let f = facts()?;
    std::fs::write(out.join("RELEASE-NOTES.md"), render_notes(&f))?;
    std::fs::write(out.join("COMPATIBILITY.md"), render_compat(&f))?;
    println!("notes written in {}", out.display());
    Ok(())
}

/// `release devkit-notices --out <folder>`: THIRD-PARTY-NOTICES.md alone (and the `cargo deny` check).
pub fn notices_only(out: &Path) -> Result<()> {
    std::fs::create_dir_all(out)?;
    std::fs::write(out.join("THIRD-PARTY-NOTICES.md"), notices()?)?;
    println!("notices written in {}", out.display());
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn facts_for_test() -> Facts {
        Facts {
            version: "1.2.0".into(),
            sdk: "1.1.0".into(),
            plugin_api: "1.1.0".into(),
            testing: "1.0.0".into(),
            api: 1,
            rust: "1.85".into(),
            plugins: vec![
                ("a.ok".into(), "1.0.0".into(), ">=1.0, <2".into(), "1".into()),
                ("b.old".into(), "1.0.0".into(), ">=0.5, <1".into(), "1".into()),
                ("c.none".into(), "1.0.0".into(), "-".into(), "-".into()),
                ("d.future".into(), "1.0.0".into(), ">=1.0, <2".into(), "2".into()),
            ],
            changes: vec![
                ("sdk".into(), "- adds x\n\n### Breaking changes\n\n- removes `y`".into()),
                ("cli".into(), "- adds z".into()),
            ],
        }
    }

    #[test]
    fn changelog_sections_fall_back_to_unreleased() {
        let t = "# C\n\n## Unreleased\n\n- next\n\n## 1.0.0\n\n- first\n";
        assert_eq!(changelog_section(t, "1.0.0").as_deref(), Some("- first"));
        assert_eq!(changelog_section(t, "2.0.0").as_deref(), Some("- next"));
        assert_eq!(changelog_section("# C\n", "1.0.0"), None);
    }

    #[test]
    fn the_notes_gather_the_breaking_changes_under_one_heading() {
        let n = render_notes(&facts_for_test());
        let b = update::breaking_section(&n).expect("breaking changes found by self-update");
        assert!(b.contains("removes `y`") && b.contains("**sdk**") && !b.contains("adds z"), "{b}");
        assert!(n.contains("- adds x") && !n.contains("### Breaking"));
        let mut f = facts_for_test();
        f.changes = vec![("cli".into(), "- adds z".into())];
        assert!(update::breaking_section(&render_notes(&f)).is_none());
        assert!(render_notes(&f).contains("## Breaking changes\n\nNone."));
    }

    #[test]
    fn the_compatibility_table_says_what_works() {
        let c = render_compat(&facts_for_test());
        assert!(c.contains("| a.ok | 1.0.0 | >=1.0, <2 | 1 | yes |"), "{c}");
        assert!(c.contains("| b.old | 1.0.0 | >=0.5, <1 | 1 | no |"));
        assert!(c.contains("| c.none | 1.0.0 | - | - | no range declared |"));
        assert!(c.contains("| d.future | 1.0.0 | >=1.0, <2 | 2 | no |"));
        assert!(c.contains("| Plugin API | 1 |") && c.contains("| Package format `.mskp` | 3 |"));
    }

    #[test]
    fn crates_of_follows_normal_dependencies_only() {
        let meta = serde_json::json!({
            "packages": [
                {"id": "r", "name": "mosaikit-server", "version": "1.0.0", "source": null},
                {"id": "a", "name": "a", "version": "1.0.0", "source": "registry", "license": "MIT", "repository": "https://a"},
                {"id": "b", "name": "b", "version": "2.0.0", "source": "registry", "license": "Apache-2.0", "repository": "https://b"},
                {"id": "t", "name": "testonly", "version": "1.0.0", "source": "registry", "license": "MIT", "repository": ""}
            ],
            "resolve": {"nodes": [
                {"id": "r", "deps": [
                    {"pkg": "a", "dep_kinds": [{"kind": null}]},
                    {"pkg": "t", "dep_kinds": [{"kind": "dev"}]}]},
                {"id": "a", "deps": [{"pkg": "b", "dep_kinds": [{"kind": null}]}]},
                {"id": "b", "deps": []}, {"id": "t", "deps": []}
            ]}
        });
        let c = crates_of(&meta, &["mosaikit-server"]);
        assert_eq!(c.iter().map(|p| p.0.as_str()).collect::<Vec<_>>(), vec!["a", "b"]);
        let text = render_notices("1.0.0", &c, &[]);
        assert!(text.contains("| MIT | 1 |") && text.contains("| b | 2.0.0 | Apache-2.0 | https://b |"));
    }

    #[test]
    fn the_sums_cover_every_archive_and_verify() {
        let d = tempfile::tempdir().unwrap();
        std::fs::write(d.path().join("mosaikit-devkit-1.0.0-linux-x86_64.tar.gz"), b"linux").unwrap();
        std::fs::write(d.path().join("mosaikit-devkit-1.0.0-windows-x86_64.zip"), b"win").unwrap();
        std::fs::write(d.path().join("notes.md"), b"x").unwrap();
        let key = mosaikit_mskp::generate_key();
        write_sums(d.path(), &key).unwrap();
        let sums = std::fs::read_to_string(d.path().join("SHA256SUMS")).unwrap();
        assert_eq!(update::parse_sums(&sums).len(), 2);
        let trusted = mosaikit_mskp::TrustedKeys::from_b64(&[mosaikit_mskp::public_key_b64(&key)]).unwrap();
        let sig = std::fs::read_to_string(d.path().join("SHA256SUMS.sig")).unwrap();
        update::check_download("mosaikit-devkit-1.0.0-windows-x86_64.zip", b"win", &sums, &sig, &trusted)
            .unwrap();
    }
}
